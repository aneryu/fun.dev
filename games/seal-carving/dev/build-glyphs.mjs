// Builds glyphs.js from the Shuowen seal-script SVGs in dev/shuowen (public domain, from
// Wikimedia Commons, "<character>-seal.svg"):  node dev/build-glyphs.mjs
//
// Each character is drawn into a square, stretched to fill its cell as seal carvers do, and
// its strokes are thinned to centre lines and redrawn at one even width (STROKE_PX), so every
// character carves alike. The result is a SIZE × SIZE bit mask per character (1 = stroke).
import { chromium } from "playwright";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SIZE = 84; // 4 px per grid unit over the 21-unit cell
const MARGIN = 2; // px left clear around the glyph inside its cell
const STROKE_PX = 5.6; // the even stroke width (1.4 grid units)
const HI = 4; // thinning resolution, per mask pixel
const dir = new URL("./shuowen/", import.meta.url);
const files = readdirSync(dir).filter((file) => file.endsWith(".svg")).sort();

const browser = await chromium.launch();
const page = await browser.newPage();
const masks = {};
for (const file of files) {
  const svg = readFileSync(new URL(file, dir), "utf8");
  // Raster at high resolution, then the ink's bounding box, stretched to the cell.
  // The ink, stretched from its bounding box to the cell, at HI × the mask's resolution.
  const big = SIZE * HI;
  const on = await page.evaluate(async ({ svg, big, margin }) => {
    const img = new Image();
    img.src = "data:image/svg+xml;base64," + btoa(unescape(encodeURIComponent(svg)));
    await img.decode();
    const full = 1200;
    const source = Object.assign(document.createElement("canvas"), { width: full, height: full });
    const g = source.getContext("2d");
    g.drawImage(img, 0, 0, full, full);
    const data = g.getImageData(0, 0, full, full).data;
    let x0 = full, y0 = full, x1 = 0, y1 = 0;
    for (let y = 0; y < full; y++) for (let x = 0; x < full; x++) {
      if (data[(y * full + x) * 4 + 3] < 128) continue;
      x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
    }
    const out = Object.assign(document.createElement("canvas"), { width: big, height: big });
    const h = out.getContext("2d");
    h.drawImage(source, x0, y0, x1 - x0 + 1, y1 - y0 + 1, margin, margin, big - 2 * margin, big - 2 * margin);
    const cell = h.getImageData(0, 0, big, big).data;
    return Array.from({ length: big * big }, (_, i) => cell[i * 4 + 3] >= 128 ? 1 : 0);
  }, { svg, big, margin: MARGIN * HI });
  // The strokes' centre lines: Zhang–Suen thinning down to a connected one-pixel skeleton.
  const skeleton = Uint8Array.from(on);
  const at = (x, y) => x < 0 || y < 0 || x >= big || y >= big ? 0 : skeleton[y * big + x];
  for (let changed = true; changed;) {
    changed = false;
    for (const phase of [0, 1]) {
      const remove = [];
      for (let y = 0; y < big; y++) for (let x = 0; x < big; x++) {
        if (!skeleton[y * big + x]) continue;
        const n = [at(x, y - 1), at(x + 1, y - 1), at(x + 1, y), at(x + 1, y + 1), at(x, y + 1), at(x - 1, y + 1), at(x - 1, y), at(x - 1, y - 1)];
        const count = n.reduce((sum, value) => sum + value, 0);
        let turns = 0;
        for (let k = 0; k < 8; k++) if (!n[k] && n[(k + 1) % 8]) turns++;
        if (count < 2 || count > 6 || turns !== 1) continue;
        if (phase === 0 ? n[0] * n[2] * n[4] || n[2] * n[4] * n[6] : n[0] * n[2] * n[6] || n[0] * n[4] * n[6]) continue;
        remove.push(y * big + x);
      }
      for (const index of remove) skeleton[index] = 0;
      if (remove.length) changed = true;
    }
  }
  // Redraw the strokes at one width around the skeleton, then sample down to the mask.
  const radius = STROKE_PX * HI / 2, reach = Math.ceil(radius);
  const thick = new Uint8Array(big * big);
  for (let y = 0; y < big; y++) for (let x = 0; x < big; x++) {
    if (!skeleton[y * big + x]) continue;
    for (let dy = -reach; dy <= reach; dy++) for (let dx = -reach; dx <= reach; dx++) {
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || ny < 0 || nx >= big || ny >= big || dx * dx + dy * dy > radius * radius) continue;
      thick[ny * big + nx] = 1;
    }
  }
  const mask = new Uint8Array(SIZE * SIZE);
  for (let y = 0; y < SIZE; y++) for (let x = 0; x < SIZE; x++) {
    let sum = 0;
    for (let j = 0; j < HI; j++) for (let i = 0; i < HI; i++) sum += thick[(y * HI + j) * big + x * HI + i];
    mask[y * SIZE + x] = sum * 2 >= HI * HI ? 1 : 0;
  }
  const bytes = new Uint8Array(Math.ceil(SIZE * SIZE / 8));
  mask.forEach((bit, i) => { if (bit) bytes[i >> 3] |= 1 << (i & 7); });
  masks[file.replace(".svg", "")] = Buffer.from(bytes).toString("base64");
}
await browser.close();

const source = `// Generated by dev/build-glyphs.mjs from the Shuowen seal-script SVGs in dev/shuowen (public
// domain, Wikimedia Commons). Each character: a GLYPH_SIZE × GLYPH_SIZE bit mask (1 = stroke),
// rows top to bottom, base64.
export const GLYPH_SIZE = ${SIZE};
export const GLYPH_MASKS = {
${Object.entries(masks).map(([name, data]) => `  "${name}": "${data}",`).join("\n")}
};
`;
writeFileSync(new URL("../glyphs.js", import.meta.url), source);
console.log(`glyphs.js: ${Object.keys(masks).length} characters`);
